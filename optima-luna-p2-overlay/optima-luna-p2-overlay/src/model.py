"""Spatially validated pseudo-label models with feature masking and ensembles.

Important: labels are generated by the project's weighted scoring rule. Metrics therefore
measure how well a model approximates that heuristic on held-out spatial blocks; they are
not evidence of physical landing safety, ice abundance, or mission success.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import joblib
import numpy as np
import pandas as pd
from sklearn.impute import SimpleImputer
from sklearn.linear_model import Ridge
from sklearn.metrics import r2_score, mean_absolute_error
from sklearn.neural_network import MLPRegressor
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.model_selection import GroupShuffleSplit
from src.config import ROOT, load_config

TARGETS = ("landing_score", "resource_score")
METADATA = {"cell_id", "row", "col", "x", "y", "lat", "lon", "true_area_km2", "data_provenance", "synthetic_seed"}


def _weighted_score(frame: pd.DataFrame, definitions: dict) -> tuple[pd.Series, pd.Series]:
    """Compute weighted mean over present finite features and available-weight confidence."""
    numerator = np.zeros(len(frame), dtype=float)
    denominator = np.zeros(len(frame), dtype=float)
    total_weight = sum(float(spec["weight"]) for spec in definitions.values())
    for name, spec in definitions.items():
        if name not in frame:
            continue
        values = pd.to_numeric(frame[name], errors="coerce").to_numpy(float)
        finite = np.isfinite(values)
        if not finite.any():
            continue
        lo, hi = np.nanpercentile(values[finite], [2, 98])
        norm = np.clip((values - lo) / max(hi - lo, 1e-9), 0, 1)
        if spec["direction"] == "lower":
            norm = 1 - norm
        elif spec["direction"] != "higher":
            raise ValueError(f"Unknown direction {spec['direction']!r} for {name}")
        weight = float(spec["weight"])
        numerator[finite] += norm[finite] * weight
        denominator[finite] += weight
    score = np.divide(numerator, denominator, out=np.full(len(frame), np.nan), where=denominator > 0)
    # Synthetic values may train the demo model, but must never count as real-data coverage.
    coverage_weight = np.zeros(len(frame), dtype=float)
    for name, spec in definitions.items():
        cov_col = f"{name}_cov"
        if name not in frame:
            continue
        finite = np.isfinite(pd.to_numeric(frame[name], errors="coerce").to_numpy(float))
        if cov_col in frame.columns:
            observed = frame[cov_col].fillna(False).astype(bool).to_numpy() & finite
        else:
            # Legacy inputs without explicit coverage flags are treated as present data.
            observed = finite
        coverage_weight[observed] += float(spec["weight"])
    confidence = coverage_weight / total_weight if total_weight else np.zeros(len(frame))
    return pd.Series(score, index=frame.index), pd.Series(confidence, index=frame.index)


def make_pseudo_labels(frame: pd.DataFrame, cfg: dict | None = None) -> pd.DataFrame:
    """Create baseline multi-criteria targets and coverage confidence."""
    cfg = cfg or load_config()
    result = frame.copy()
    for target, key in (("landing_score", "landing"), ("resource_score", "resource")):
        score, confidence = _weighted_score(result, cfg["scoring"][key])
        result[target] = score
        result[f"{target.replace('_score', '')}_confidence"] = confidence
    return result


def spatial_block_groups(frame: pd.DataFrame, block_size_m: float = 10_000) -> np.ndarray:
    """Assign whole projected x/y blocks to shared group IDs to prevent spatial leakage."""
    if block_size_m <= 0:
        raise ValueError("block_size_m must be positive")
    if not {"x", "y"}.issubset(frame.columns):
        raise ValueError("spatial validation needs projected x and y columns")
    bx = np.floor(pd.to_numeric(frame.x).to_numpy(float) / block_size_m).astype(np.int64)
    by = np.floor(pd.to_numeric(frame.y).to_numpy(float) / block_size_m).astype(np.int64)
    # Structured pair -> stable integer group, independent of dataframe row order.
    pairs = np.column_stack([bx, by])
    return pd.factorize(pd.MultiIndex.from_arrays([pairs[:, 0], pairs[:, 1]]), sort=True)[0]


def _feature_columns(frame: pd.DataFrame) -> list[str]:
    return [c for c in frame.select_dtypes(include=[np.number]).columns
            if c not in METADATA and c not in TARGETS and not c.endswith("_confidence")
            and not c.endswith("_cov")]


def _mask_features(X: pd.DataFrame, rng: np.random.Generator, rate: float) -> pd.DataFrame:
    """Randomly hide feature cells during training to simulate patchy layer availability."""
    if not 0 <= rate < 1:
        raise ValueError("mask_rate must be in [0, 1)")
    masked = X.copy()
    if rate:
        # Hide complete feature layers (columns), emulating a missing sensor/product.
        drop_layers = rng.random(masked.shape[1]) < rate
        if drop_layers.any():
            masked.loc[:, masked.columns[drop_layers]] = np.nan
        # Keep a small cell-level component to mimic patchy coverage within a layer.
        cell_mask = rng.random(masked.shape) < (rate * 0.15)
        masked = masked.mask(cell_mask)
    return masked


def _make_pipeline(kind: str, seed: int) -> Pipeline:
    # keep_empty_features preserves a completely-missing sensor layer after masking.
    imputer = SimpleImputer(strategy="median", add_indicator=True, keep_empty_features=True)
    if kind == "baseline":
        estimator = Ridge(alpha=1.0)
    elif kind == "mlp":
        estimator = MLPRegressor(hidden_layer_sizes=(64, 32), activation="relu", solver="adam",
                                 alpha=1e-3, learning_rate_init=1e-3, max_iter=100,
                                 batch_size=256, early_stopping=True, validation_fraction=0.15,
                                 n_iter_no_change=10, random_state=seed)
    else:
        raise ValueError("kind must be 'baseline' or 'mlp'")
    return Pipeline([("imputer", imputer), ("scale", StandardScaler()), ("model", estimator)])


def _fit_target(frame: pd.DataFrame, features: list[str], target: str, groups: np.ndarray,
                *, kind: str, seed: int, mask_rate: float, eval_mask_rate: float,
                ensemble_size: int) -> tuple[list[Pipeline], dict]:
    y = pd.to_numeric(frame[target], errors="coerce")
    valid = y.notna().to_numpy()
    X = frame.loc[valid, features].reset_index(drop=True)
    yv = y.loc[valid].to_numpy(float)
    gv = groups[valid]
    if len(np.unique(gv)) < 3:
        raise ValueError("Need at least 3 distinct spatial blocks for train/validation/test split")
    # 20% held out spatial blocks for final test; remaining blocks supply training and val.
    splitter = GroupShuffleSplit(n_splits=1, test_size=0.2, random_state=seed)
    trainval_idx, test_idx = next(splitter.split(X, yv, groups=gv))
    trainval_groups = gv[trainval_idx]
    splitter2 = GroupShuffleSplit(n_splits=1, test_size=0.2, random_state=seed + 1)
    train_rel, val_rel = next(splitter2.split(X.iloc[trainval_idx], yv[trainval_idx], groups=trainval_groups))
    train_idx, val_idx = trainval_idx[train_rel], trainval_idx[val_rel]
    # Assert disjoint spatial blocks; this is the central leakage guard.
    if set(gv[train_idx]) & set(gv[val_idx]) or set(gv[train_idx]) & set(gv[test_idx]) or set(gv[val_idx]) & set(gv[test_idx]):
        raise AssertionError("spatial group leakage detected")

    # Bound MLP fit time on the 290k-cell cap while retaining a broad spatial sample.
    # Evaluation below always uses every held-out validation/test cell.
    n_train_available = len(train_idx)
    if kind == "mlp" and len(train_idx) > 30_000:
        sample_rng = np.random.default_rng(seed + 404)
        train_idx = np.sort(sample_rng.choice(train_idx, size=30_000, replace=False))

    models: list[Pipeline] = []
    val_scores, test_scores = [], []
    for member in range(ensemble_size):
        member_seed = seed + member * 101
        rng = np.random.default_rng(member_seed)
        x_train = _mask_features(X.iloc[train_idx], rng, mask_rate)
        model = _make_pipeline(kind, member_seed)
        model.fit(x_train, yv[train_idx])
        models.append(model)
        val_pred = np.clip(model.predict(X.iloc[val_idx]), 0.0, 1.0)
        test_pred = np.clip(model.predict(X.iloc[test_idx]), 0.0, 1.0)
        val_scores.append(float(r2_score(yv[val_idx], val_pred)) if len(val_idx) > 1 else float("nan"))
        test_scores.append(float(r2_score(yv[test_idx], test_pred)) if len(test_idx) > 1 else float("nan"))

    # The ensemble is the deployed prediction; metrics use mean ensemble output.
    val_X = X.iloc[val_idx]
    test_X = X.iloc[test_idx]
    val_pred = np.clip(np.mean([m.predict(val_X) for m in models], axis=0), 0.0, 1.0)
    test_pred = np.clip(np.mean([m.predict(test_X) for m in models], axis=0), 0.0, 1.0)
    masked_rng = np.random.default_rng(seed + 9901)
    val_masked = _mask_features(val_X, masked_rng, eval_mask_rate)
    test_masked = _mask_features(test_X, masked_rng, eval_mask_rate)
    val_pred_masked = np.clip(np.mean([m.predict(val_masked) for m in models], axis=0), 0.0, 1.0)
    test_pred_masked = np.clip(np.mean([m.predict(test_masked) for m in models], axis=0), 0.0, 1.0)
    metrics = {
        "target": target, "kind": kind, "training_mask_rate": mask_rate,
        "evaluation_mask_rate": eval_mask_rate,
        "n_train": int(len(train_idx)), "n_train_available_before_mlp_cap": int(n_train_available),
        "n_validation": int(len(val_idx)), "n_test": int(len(test_idx)),
        "train_spatial_blocks": int(len(set(gv[train_idx]))),
        "validation_spatial_blocks": int(len(set(gv[val_idx]))),
        "test_spatial_blocks": int(len(set(gv[test_idx]))),
        "validation_r2": float(r2_score(yv[val_idx], val_pred)) if len(val_idx) > 1 else None,
        "test_r2": float(r2_score(yv[test_idx], test_pred)) if len(test_idx) > 1 else None,
        "validation_r2_with_masked_inputs": float(r2_score(yv[val_idx], val_pred_masked)) if len(val_idx) > 1 else None,
        "test_r2_with_masked_inputs": float(r2_score(yv[test_idx], test_pred_masked)) if len(test_idx) > 1 else None,
        "test_mae": float(mean_absolute_error(yv[test_idx], test_pred)),
        "member_test_r2": test_scores,
        "interpretation": "R2 against scoring-rule pseudo-labels; not empirical mission-performance accuracy.",
    }
    return models, metrics


def train_models(
    features: pd.DataFrame,
    *,
    mask_rate: float = 0.15,
    ensemble_size: int = 3,
    seed: int = 20261121,
    block_size_m: float = 10_000,
    output_dir: str | Path | None = None,
    cfg: dict | None = None,
) -> tuple[pd.DataFrame, dict]:
    """Train a Ridge baseline and 2-layer MLP ensemble with spatial holdouts.

    The Ridge baseline is trained without synthetic feature masking. The MLP is trained
    with complete-layer and cell-level masking. Both are evaluated on clean and masked
    holdout inputs. Large MLP fits are capped to a deterministic 30k-cell sample, while
    the validation and test metrics always use all held-out spatial-block cells.
    """
    if ensemble_size < 1:
        raise ValueError("ensemble_size must be at least 1")
    cfg = cfg or load_config()
    labelled = make_pseudo_labels(features, cfg)
    feature_cols = _feature_columns(labelled)
    if not feature_cols:
        raise ValueError("No numeric model features found")
    groups = spatial_block_groups(labelled, block_size_m)
    artifacts: dict = {"metadata": {
        "label_type": "weighted-scoring pseudo-labels", "spatial_block_size_m": block_size_m,
        "seed": seed, "ensemble_size": ensemble_size, "feature_columns": feature_cols,
        "mlp_training_sample_cap": 30000,
        "warning": "R2 evaluates imitation/generalisation of this scoring heuristic, not scientific truth.",
    }, "metrics": {}, "models": {}}
    predictions = labelled.copy()
    for target in TARGETS:
        for kind, training_rate, members in (("baseline", 0.0, 1), ("mlp", mask_rate, ensemble_size)):
            models, metrics = _fit_target(
                labelled, feature_cols, target, groups, kind=kind, seed=seed,
                mask_rate=training_rate, eval_mask_rate=mask_rate, ensemble_size=members,
            )
            key = f"{target}/{kind}"
            artifacts["metrics"][key] = metrics
            artifacts["models"][key] = models
            all_X = labelled[feature_cols]
            member_preds = np.clip(np.vstack([m.predict(all_X) for m in models]), 0.0, 1.0)
            predictions[f"{target}_{kind}_pred"] = member_preds.mean(axis=0)
            predictions[f"{target}_{kind}_uncertainty"] = (
                member_preds.std(axis=0, ddof=1) if len(models) > 1 else np.zeros(len(all_X))
            )
    # Stable columns consumed by pairing.py and downstream dashboard code.
    predictions["landing_score"] = predictions["landing_score_mlp_pred"]
    predictions["resource_score"] = predictions["resource_score_mlp_pred"]
    predictions["confidence"] = predictions[["landing_confidence", "resource_confidence"]].mean(axis=1)
    predictions["landing_uncertainty"] = predictions["landing_score_mlp_uncertainty"]
    predictions["resource_uncertainty"] = predictions["resource_score_mlp_uncertainty"]
    out_dir = Path(output_dir or ROOT / "models")
    out_dir.mkdir(parents=True, exist_ok=True)
    # Persist the Ridge baseline, masked MLP ensemble, and machine-readable metrics.
    for key, models in artifacts["models"].items():
        safe = key.replace("/", "_")
        joblib.dump(models, out_dir / f"{safe}.joblib")
    (out_dir / "metrics.json").write_text(json.dumps({"metadata": artifacts["metadata"], "metrics": artifacts["metrics"]}, indent=2), encoding="utf-8")
    predictions.attrs["model_metrics"] = artifacts["metrics"]
    return predictions, artifacts["metrics"]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=ROOT / "data/processed/features.parquet")
    parser.add_argument("--output", type=Path, default=ROOT / "data/processed/scored_features.parquet")
    parser.add_argument("--mask-rate", type=float, default=0.15)
    args = parser.parse_args()
    data = pd.read_parquet(args.input)
    predictions, metrics = train_models(data, mask_rate=args.mask_rate)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    predictions.to_parquet(args.output, index=False)
    print(json.dumps(metrics, indent=2))

if __name__ == "__main__": main()
